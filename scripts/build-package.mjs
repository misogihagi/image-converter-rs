import { execSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const wasmCrateDir = path.join(rootDir, "crates", "wasm");
const pkgDir = path.join(rootDir, "packages", "image-converter-wasm");
const distNodeDir = path.join(pkgDir, "dist", "node");
const distWebDir = path.join(pkgDir, "dist", "web");

console.log("🔨 Building image-converter-wasm package...");

// Ensure output directories exist
fs.mkdirSync(distNodeDir, { recursive: true });
fs.mkdirSync(distWebDir, { recursive: true });

// 1. Build for Node.js
console.log("\n📦 [1/2] Building for Node.js (--target nodejs)...");
execSync(`npx wasm-pack build "${wasmCrateDir}" --target nodejs --out-dir "${distNodeDir}"`, {
  stdio: "inherit",
  cwd: rootDir,
});

// 2. Build for Web / Bundler
console.log("\n🌐 [2/2] Building for Web / Modern Bundlers (--target web)...");
execSync(`npx wasm-pack build "${wasmCrateDir}" --target web --out-dir "${distWebDir}"`, {
  stdio: "inherit",
  cwd: rootDir,
});

// Remove unwanted package.json generated by wasm-pack in subdirs to avoid confusion
const nodePkg = path.join(distNodeDir, "package.json");
if (fs.existsSync(nodePkg)) {
  fs.unlinkSync(nodePkg);
}
const webPkg = path.join(distWebDir, "package.json");
if (fs.existsSync(webPkg)) {
  fs.unlinkSync(webPkg);
}

// Remove nested .gitignore generated by wasm-pack so npm pack won't ignore them
const nodeGitignore = path.join(distNodeDir, ".gitignore");
if (fs.existsSync(nodeGitignore)) {
  fs.unlinkSync(nodeGitignore);
}
const webGitignore = path.join(distWebDir, ".gitignore");
if (fs.existsSync(webGitignore)) {
  fs.unlinkSync(webGitignore);
}

console.log("\n✅ image-converter-wasm build completed successfully!");
